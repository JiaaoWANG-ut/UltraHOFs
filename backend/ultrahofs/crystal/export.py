"""Structure exporters: CIF (P1 / symmetrised), POSCAR, extended XYZ, LAMMPS data, PDB."""

from __future__ import annotations

import io
from datetime import UTC, datetime

import numpy as np
from ase import Atoms
from ase.io import write as ase_write
from pymatgen.core import Lattice, Structure
from pymatgen.io.cif import CifWriter
from pymatgen.io.vasp import Poscar

from .. import __version__

FORMATS = {
    "cif": ("CIF (P1)", "chemical/x-cif", "cif"),
    "cif_sym": ("CIF (symmetrised)", "chemical/x-cif", "cif"),
    "poscar": ("VASP POSCAR", "text/plain", "vasp"),
    "xyz": ("Extended XYZ", "chemical/x-xyz", "xyz"),
    "lammps": ("LAMMPS data", "text/plain", "data"),
    "pdb": ("PDB", "chemical/x-pdb", "pdb"),
}


def to_structure(atoms: Atoms) -> Structure:
    return Structure(Lattice(np.asarray(atoms.cell.array)), atoms.get_chemical_symbols(), atoms.positions,
                     coords_are_cartesian=True)


def _banner(title: str) -> str:
    stamp = datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    return (f"# {title}\n# Generated by UltraHOFs {__version__} (Ultra-X / 知声无界) {stamp}\n"
            "# Hypothetical structure unless stated otherwise; not experimentally verified.\n")


def write_cif(atoms: Atoms, title: str = "UltraHOFs structure", symprec: float | None = None) -> str:
    st = to_structure(atoms)
    text = str(CifWriter(st, symprec=symprec)) if symprec else str(CifWriter(st))
    data_name = "".join(ch if ch.isalnum() or ch in "-_" else "_" for ch in title)[:60] or "ultrahofs"
    lines = text.splitlines()
    if lines and lines[0].startswith("# generated"):
        lines = lines[1:]
    lines = [f"data_{data_name}" if ln.startswith("data_") else ln for ln in lines]
    return _banner(title) + "\n".join(lines) + "\n"


def export(atoms: Atoms, fmt: str, title: str = "UltraHOFs structure") -> str:
    if fmt == "cif":
        return write_cif(atoms, title)
    if fmt == "cif_sym":
        try:
            return write_cif(atoms, title, symprec=0.1)
        except Exception:  # noqa: BLE001
            return write_cif(atoms, title)
    if fmt == "poscar":
        st = to_structure(atoms).get_sorted_structure()
        return Poscar(st, comment=f"{title} | UltraHOFs").get_str()
    if fmt == "xyz":
        buf = io.StringIO()
        ase_write(buf, atoms, format="extxyz")
        return buf.getvalue()
    if fmt == "lammps":
        buf = io.StringIO()
        species = sorted(set(atoms.get_chemical_symbols()))
        ase_write(buf, atoms, format="lammps-data", atom_style="atomic", specorder=species, masses=True)
        return f"# {title} | UltraHOFs (atom types: {' '.join(species)})\n" + buf.getvalue().split("\n", 1)[1]
    if fmt == "pdb":
        buf = io.StringIO()
        ase_write(buf, atoms, format="proteindatabank")
        return f"REMARK   1 {title} | UltraHOFs\n" + buf.getvalue()
    raise ValueError(f"unknown format '{fmt}'")


def cell_dict(atoms: Atoms) -> dict:
    a, b, c, al, be, ga = atoms.cell.cellpar()
    return {"a": round(a, 4), "b": round(b, 4), "c": round(c, 4), "alpha": round(al, 3),
            "beta": round(be, 3), "gamma": round(ga, 3), "volume": round(float(atoms.cell.volume), 2)}


def density(atoms: Atoms) -> float:
    return round(float(atoms.get_masses().sum() * 1.66053906660 / atoms.cell.volume), 4)
