const saved = localStorage.getItem('uh_lang');
i18n.use(initReactI18next).init({
  resources: { 'zh-CN': { translation: zh }, 'en-US': { translation: en } },
  lng: saved || (navigator.language.startsWith('zh') ? 'zh-CN' : 'zh-CN'),
  fallbackLng: 'zh-CN',
  interpolation: { escapeValue: false },
  returnObjects: true,
});

export function setLanguage(lng: 'zh-CN' | 'en-US') {
  localStorage.setItem('uh_lang', lng);
  i18n.changeLanguage(lng);
  document.documentElement.lang = lng;
}

